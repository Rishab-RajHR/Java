public class Switch {
    public static void main(String1[] args) {
        int age = 20;
        switch (age) 
        {
          case 10:
            System.out.println("Your Age is 10");
            break;
          case 20:
            System.out.println("Your Age is 20");
            break;
     
          case 30:
            System.out.println("Your Age is 30");
            break;

          default:
            System.out.println("Invalid Age");;
        }
    }
}
